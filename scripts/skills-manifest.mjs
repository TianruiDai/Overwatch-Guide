import {
  createHash
} from 'node:crypto';
import {
  mkdir,
  readFile,
  readdir,
  writeFile,
  stat
} from 'node:fs/promises';
import path from 'node:path';
import {
  fileURLToPath
} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const skillsRoot = path.join(root, 'skills');

async function walk(dir, base = dir) {
  const out = [];
  for (const entry of await readdir(dir, {
      withFileTypes: true
    })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full, base));
    else if (entry.isFile()) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

function parseFrontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(text);
  if (!m) return {
    meta: {},
    body: text
  };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const i = line.indexOf(':');
    if (i < 0) continue;
    const key = line.slice(0, i).trim();
    let value = line.slice(i + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    meta[key] = value;
  }
  return {
    meta,
    body: m[2].trim()
  };
}

const stageSkills = [{
  id: 'overwatch-knowledge-distiller',
  dir: 'overwatch-knowledge-distiller',
  stages: ['distill', 'version']
}, {
  id: 'overwatch-read-match',
  dir: 'overwatch-read-match',
  stages: ['read-match']
}, {
  id: 'overwatch-kb-review',
  dir: 'overwatch-kb-review',
  stages: ['fight', 'coach']
}];

const skills = [];
for (const item of stageSkills) {
  const skillDir = path.join(skillsRoot, item.dir);
  const skillPath = path.join(skillDir, 'SKILL.md');
  const raw = await readFile(skillPath, 'utf8');
  const {
    meta,
    body
  } = parseFrontmatter(raw);
  const files = await walk(skillDir);
  const fileHashes = {};
  for (const rel of files) {
    const bytes = await readFile(path.join(skillDir, rel));
    fileHashes[rel] = createHash('sha256').update(bytes).digest('hex');
  }
  const sha256 = createHash('sha256').update(raw).digest('hex');
  skills.push({
    id: item.id,
    name: meta.name || item.id,
    description: meta.description || '',
    version: meta.version || '1.0.0',
    path: 'skills/' + item.dir + '/SKILL.md',
    stages: item.stages,
    sha256,
    body,
    files: fileHashes
  });
}

const manifest = {
  generatedAt: new Date().toISOString(),
  contractVersion: 'v2.0.0',
  skills
};

await mkdir(path.join(root, 'shared'), {
  recursive: true
});
const jsonPath = path.join(skillsRoot, 'manifest.json');
await writeFile(jsonPath, JSON.stringify(manifest, null, 2) + '\n');

const js = `/* generated by scripts/skills-manifest.mjs — do not edit by hand */
export const CONTRACT_VERSION = ${JSON.stringify(manifest.contractVersion)};
export const SKILLS = ${JSON.stringify(skills, null, 2)};
export const SKILL_BY_ID = Object.fromEntries(SKILLS.map(s => [s.id, s]));
export const STAGE_SKILL = {
  distill: 'overwatch-knowledge-distiller',
  version: 'overwatch-knowledge-distiller',
  'read-match': 'overwatch-read-match',
  fight: 'overwatch-kb-review',
  coach: 'overwatch-kb-review'
};
`;
await writeFile(path.join(root, 'shared', 'skills-manifest.mjs'), js);
console.log('Wrote skills/manifest.json and shared/skills-manifest.mjs (' + skills.length + ' skills).');
